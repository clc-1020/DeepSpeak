package com.companion.chat.domain.alarm

/**
 * 判断用户一句话是否是「要我在某个时间做点什么」的指令。任务 3.3 / 3.8（纯函数，可 JVM 单测）
 *
 * 仅当含明确的指令提示词时才尝试排期，避免把闲聊里随口提到的时间都当提醒。
 * 与 [ReminderParser] 配合：先 [matches] 再 [ReminderParser.parse]，两者都过才设闹钟。
 *
 * 任务 3.8 扩充：把「到点给我发消息 / 通知我 / 叫我 / 提醒 / 记着 / 闹钟」等口语说法一次收全。
 * 因为最终还要能解析出时间才真正排期，提示词放宽不会造成误排，只影响"要不要尝试解析"。
 */
object ReminderIntent {

    /** 指令提示词（命中任一即视为意图；再叠加「能解析出时间」才真正排期）。 */
    private val CUES = listOf(
        // 呼唤 / 叫醒
        "叫我", "叫醒", "喊我", "喊醒", "唤醒我", "叫我一下", "喊一声",
        // 提醒 / 记着
        "提醒我", "提醒一下", "提醒下", "提个醒", "提示我", "备忘", "记一下", "记着", "记住", "记得",
        "别忘", "别忘记", "不要忘记", "帮我记",
        // 闹钟 / 定时
        "闹钟", "闹铃", "定时", "定个时", "计时",
        // 发消息 / 通知 / 冒泡
        "发条信息", "发条消息", "发个信息", "发个消息", "发消息", "发信息", "发给我", "给我发",
        "来条消息", "来条信息", "来消息", "来信息", "通知我", "通知一下", "弹个通知",
        "推送给我", "推给我", "敲我", "戳我", "滴滴我", "滴我", "艾特我",
        "找我", "找我聊", "吱一声", "冒个泡", "说一声"
    )

    /**
     * 否定 / 叙述性说法：这些不是"让系统排期"，而是闲聊在提过去。
     * 例：「我记得昨天 7 点…」「你还记得吗」「我记不清」——一律不排。
     */
    private val NEGATIONS = listOf(
        "我记得", "还记得", "不记得", "没记得", "记不清", "记不记得", "忘记了"
    )

    fun matches(text: String): Boolean {
        val t = text.trim()
        if (t.isEmpty()) return false
        if (NEGATIONS.any { t.contains(it) }) return false
        return CUES.any { t.contains(it) }
    }
}